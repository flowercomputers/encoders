//! Writes the generated artifacts: `weights.bin` (rows, one per slot, padded
//! to whole cache lines), `verify.bin` (per-slot verifier with the row
//! exponent packed into the low byte), `seeds.bin` and `model_constants.rs`.

use std::{fs, path::Path};

use crate::{Error, Layout, Quant, phf::Phf, tokenizer::Spec};

/// Largest row exponent emitted; must not exceed `ese::accum::MAX_ROW_EXP`.
pub(crate) const MAX_ROW_EXP: u32 = 8;

pub(crate) struct Emit<'a> {
    pub out: &'a Path,
    pub dims: usize,
    pub quant: Quant,
    pub phf: &'a Phf,
    /// One f32 row per vocabulary id.
    pub rows: &'a [Vec<f32>],
    /// Key index (as passed to the PHF) -> vocabulary id.
    pub entry_row: &'a [usize],
    pub spec: &'a Spec,
    pub layout: &'a Layout,
    pub model_id: &'a str,
    pub revision: &'a str,
    pub native_dims: usize,
    /// Widths the model was trained at, empty if truncation is unsupported
    /// or unknown.
    pub truncation_points: &'a [usize],
}

/// What the test-data generator needs to reproduce the quantization error.
#[cfg_attr(not(feature = "test-data"), allow(dead_code))]
pub(crate) struct QuantInfo {
    /// Per vocabulary id.
    pub row_exp: Vec<u8>,
    /// Per column; 0 for f32.
    pub col_step: Vec<f32>,
}

pub(crate) fn write(e: &Emit) -> Result<QuantInfo, Error> {
    let row_exp = row_exponents(e.rows, e.dims, e.quant);
    let (qmin, qscale) = quant_params(e.rows, &row_exp, e.dims, e.quant);
    let esz = e.quant.elem_size();
    // Rows are padded to a multiple of 64 bytes so each one starts on a
    // cache line; the runtime's `#[repr(C, align(64))]` slot has this size.
    let row_stride = (e.dims * esz).next_multiple_of(64);
    let phf = e.phf;

    let mut rows_bin: Vec<u8> = Vec::with_capacity(phf.table_size * row_stride);
    let mut verify_bin: Vec<u8> = Vec::with_capacity(phf.table_size * 8);
    let zero = vec![0.0f32; e.dims];
    let mut scaled = vec![0.0f32; e.dims];
    for slot in 0..phf.table_size {
        let (row, exp) = match phf.slots[slot] {
            Some(entry) => {
                let id = e.entry_row[entry];
                (e.rows[id].as_slice(), row_exp[id])
            }
            None => (zero.as_slice(), 0),
        };
        scale_row(row, exp, &mut scaled);
        quantize_into(&mut rows_bin, &scaled, &qmin, &qscale, e.quant);
        rows_bin.resize((slot + 1) * row_stride, 0);
        let v = ese::phf::pack_verifier(phf.verify[slot], exp);
        verify_bin.extend_from_slice(&v.to_le_bytes());
    }
    fs::write(e.out.join("weights.bin"), &rows_bin)?;
    fs::write(e.out.join("verify.bin"), &verify_bin)?;

    let mut seeds: Vec<u8> = Vec::with_capacity(phf.num_buckets * 2);
    for s in &phf.seeds {
        seeds.extend_from_slice(&s.to_le_bytes());
    }
    fs::write(e.out.join("seeds.bin"), &seeds)?;

    let spec = e.spec;
    let unk_exp = row_exp[spec.unk_id];
    scale_row(&e.rows[spec.unk_id], unk_exp, &mut scaled);
    let unk = format_param(&scaled, &qmin, &qscale, e.quant);
    let (qmin_str, qscale_str) = match e.quant {
        Quant::F32 => (
            "[0.0; DIMENSIONS]".to_string(),
            "[1.0; DIMENSIONS]".to_string(),
        ),
        _ => (format!("{qmin:?}"), format!("{qscale:?}")),
    };
    let row_exp_max = row_exp.iter().copied().max().unwrap_or(0);
    // WordPiece never tries a piece longer than the longest vocabulary entry
    // (measured without the subword prefix). Phrase tokens contain spaces and
    // never reach WordPiece, so they do not count.
    let max_token_bytes = spec
        .vocab
        .iter()
        .filter(|(t, _)| !t.contains(' '))
        .map(|(t, _)| {
            t.strip_prefix(spec.subword_prefix.as_str())
                .unwrap_or(t)
                .len()
        })
        .max()
        .unwrap_or(0);
    let specials: Vec<&str> = spec.special_tokens.iter().map(String::as_str).collect();
    let mut phrases: Vec<&str> = spec.phrases.iter().map(String::as_str).collect();
    phrases.sort_unstable();
    fs::write(e.out.join("phrases.txt"), phrases.join("\n"))?;
    let max_tokens = spec.max_tokens.unwrap_or(0);
    // model2vec cuts the text to `max_length * median_token_length` characters
    // before tokenizing; only on the identifier-splitting path, which is the
    // one checked against model2vec.
    let max_chars = if e.layout.framework == "model2vec" && spec.split_identifiers {
        max_tokens * spec.median_token_len
    } else {
        0
    };
    let constants = format!(
        r#"// Generated by ese-build. Do not edit.
pub const MODEL_ID: &str = {model_id:?};
pub const MODEL_REVISION: &str = {revision:?};
pub const DIMENSIONS: usize = {dims};
pub const NATIVE_DIMENSIONS: usize = {native_dims};
/// Widths the model was trained at (Matryoshka); empty when truncation is
/// unsupported or unknown.
pub const TRUNCATION_POINTS: &[usize] = &{trunc:?};
pub const MATRYOSHKA: bool = {matryoshka};
pub const VOCAB_SIZE: usize = {vocab_size};
pub type Elem = {elem};
pub type Param = [Elem; DIMENSIONS];
pub const TABLE_SIZE: usize = {table_size};
pub const TABLE_MASK: usize = {table_mask};
pub const NUM_BUCKETS: usize = {num_buckets};
pub const ROW_STRIDE: usize = {row_stride};
/// Largest per-row exponent packed into `verify.bin`.
pub const ROW_EXP_MAX: u8 = {row_exp_max};
pub const QUANT_MIN: [f32; DIMENSIONS] = {qmin_str};
pub const QUANT_SCALE: [f32; DIMENSIONS] = {qscale_str};
pub const UNK: Param = {unk};
pub const UNK_EXP: u8 = {unk_exp};
pub const UNK_TOKEN: &str = {unk_token:?};
pub const DROP_UNK: bool = {drop_unk};
pub const NORMALIZE: bool = {normalize};
pub const LOWERCASE: bool = {lowercase};
pub const STRIP_ACCENTS: bool = {strip_accents};
pub const HANDLE_CHINESE_CHARS: bool = {cjk};
pub const CLEAN_TEXT: bool = {clean_text};
pub const SUBWORD_PREFIX: &str = {prefix:?};
pub const MAX_WORD_LEN: usize = {max_word_len};
/// Bytes in the longest vocabulary entry, without the subword prefix.
pub const MAX_TOKEN_BYTES: usize = {max_token_bytes};
pub const SPECIAL_TOKENS: &[&str] = &{specials:?};
pub const SPLIT_IDENTIFIERS: bool = {split_identifiers};
pub const HAS_PHRASES: bool = {has_phrases};
/// Truncation from `tokenizer.json` (0 for none).
pub const MAX_TOKENS: usize = {max_tokens};
/// model2vec's character pre-cut (0 for none).
pub const MAX_CHARS: usize = {max_chars};
"#,
        split_identifiers = spec.split_identifiers,
        has_phrases = !spec.phrases.is_empty(),
        model_id = e.model_id,
        revision = e.revision,
        dims = e.dims,
        native_dims = e.native_dims,
        trunc = e.truncation_points,
        matryoshka = e.truncation_points.iter().any(|&d| d < e.native_dims),
        vocab_size = spec.vocab.len(),
        elem = e.quant.elem_name(),
        table_size = phf.table_size,
        table_mask = phf.table_size - 1,
        num_buckets = phf.num_buckets,
        unk_token = spec.unk_token,
        drop_unk = e.layout.drop_unk,
        normalize = e.layout.normalize,
        lowercase = spec.lowercase,
        strip_accents = spec.strip_accents,
        cjk = spec.handle_chinese_chars,
        clean_text = spec.clean_text,
        prefix = spec.subword_prefix,
        max_word_len = spec.max_word_len,
        max_token_bytes = max_token_bytes,
    );
    fs::write(e.out.join("model_constants.rs"), constants)?;
    Ok(QuantInfo {
        row_exp,
        col_step: match e.quant {
            Quant::F32 => vec![0.0; e.dims],
            _ => qscale,
        },
    })
}

#[inline]
fn scale_row(row: &[f32], exp: u8, out: &mut [f32]) {
    let f = (1u32 << exp) as f32;
    for (o, &v) in out.iter_mut().zip(row) {
        *o = v * f;
    }
}

/// Per-row power-of-two exponent: rows much smaller than a typical row are
/// scaled up by `2^exp` before quantization so they keep their resolution.
/// A row's size is its largest value relative to that column's full range,
/// and the reference is the median row.
///
/// Boosted rows take a slower f32 path at runtime, so exponents are rationed:
/// a row within 8x of the median keeps exponent 0 (it already has 5+ of its
/// 8 bits). An untrained `[UNK]` (1/100 of typical) or a SIF-down-weighted
/// frequent token (1/25) still gets its boost. Identity for f32.
fn row_exponents(rows: &[Vec<f32>], dims: usize, quant: Quant) -> Vec<u8> {
    if quant.levels().is_none() || rows.is_empty() {
        return vec![0; rows.len()];
    }
    let mut mn = vec![f32::INFINITY; dims];
    let mut mx = vec![f32::NEG_INFINITY; dims];
    for row in rows {
        for ((lo, hi), &v) in mn.iter_mut().zip(mx.iter_mut()).zip(row) {
            *lo = lo.min(v);
            *hi = hi.max(v);
        }
    }
    let range: Vec<f32> = mn
        .iter()
        .zip(&mx)
        .map(|(lo, hi)| (hi - lo).max(f32::EPSILON))
        .collect();
    let rho: Vec<f32> = rows
        .iter()
        .map(|row| {
            row.iter()
                .zip(&range)
                .map(|(v, r)| v.abs() / r)
                .fold(0.0f32, f32::max)
        })
        .collect();
    let mut nonzero: Vec<f32> = rho.iter().copied().filter(|&r| r > 0.0).collect();
    if nonzero.is_empty() {
        return vec![0; rows.len()];
    }
    nonzero.sort_by(|a, b| a.partial_cmp(b).unwrap());
    let rho_ref = nonzero[nonzero.len() / 2];
    rho.iter()
        .map(|&r| {
            if r <= 0.0 {
                0
            } else {
                let e = (rho_ref / r).log2().floor().clamp(0.0, MAX_ROW_EXP as f32) as u8;
                if e < 3 { 0 } else { e }
            }
        })
        .collect()
}

/// Per-column `(min, scale)` over the exponent-scaled rows such that
/// `scaled ≈ min[i] + q * scale[i]`. Identity for f32. Each dimension gets
/// its own range because PCA columns differ in magnitude by several times.
fn quant_params(
    rows: &[Vec<f32>],
    row_exp: &[u8],
    dims: usize,
    quant: Quant,
) -> (Vec<f32>, Vec<f32>) {
    let Some(levels) = quant.levels() else {
        return (vec![0.0; dims], vec![1.0; dims]);
    };
    let mut mn = vec![f32::INFINITY; dims];
    let mut mx = vec![f32::NEG_INFINITY; dims];
    for (row, &exp) in rows.iter().zip(row_exp) {
        let f = (1u32 << exp) as f32;
        for ((lo, hi), &v) in mn.iter_mut().zip(mx.iter_mut()).zip(row) {
            let v = v * f;
            *lo = lo.min(v);
            *hi = hi.max(v);
        }
    }
    let mut scale = Vec::with_capacity(dims);
    for (lo, hi) in mn.iter_mut().zip(&mx) {
        let range = *hi - *lo;
        if !range.is_finite() || range.abs() < f32::EPSILON {
            *lo = lo.min(0.0);
            scale.push(1.0);
        } else {
            scale.push(range / levels);
        }
    }
    (mn, scale)
}

fn quantize_into(out: &mut Vec<u8>, row: &[f32], min: &[f32], scale: &[f32], quant: Quant) {
    match quant {
        Quant::F32 => {
            for v in row {
                out.extend_from_slice(&v.to_le_bytes());
            }
        }
        Quant::U16 => {
            for ((&v, &mn), &sc) in row.iter().zip(min).zip(scale) {
                let q = ((v - mn) / sc).round().clamp(0.0, 65535.0) as u16;
                out.extend_from_slice(&q.to_le_bytes());
            }
        }
        Quant::U8 => {
            for ((&v, &mn), &sc) in row.iter().zip(min).zip(scale) {
                out.push(((v - mn) / sc).round().clamp(0.0, 255.0) as u8);
            }
        }
    }
}

fn format_param(row: &[f32], min: &[f32], scale: &[f32], quant: Quant) -> String {
    match quant {
        Quant::F32 => format!("{row:?}"),
        Quant::U16 => {
            let q: Vec<u16> = row
                .iter()
                .zip(min)
                .zip(scale)
                .map(|((&v, &mn), &sc)| ((v - mn) / sc).round().clamp(0.0, 65535.0) as u16)
                .collect();
            format!("{q:?}")
        }
        Quant::U8 => {
            let q: Vec<u8> = row
                .iter()
                .zip(min)
                .zip(scale)
                .map(|((&v, &mn), &sc)| ((v - mn) / sc).round().clamp(0.0, 255.0) as u8)
                .collect();
            format!("{q:?}")
        }
    }
}
