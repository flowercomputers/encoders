//! Character classes and BERT-style normalization from precomputed
//! tables.
//!
//! The `tokenizers` crate's `BertNormalizer` needs, per character: is it a
//! control, whitespace or punctuation; is it a CJK ideograph; what does it
//! become after NFD with nonspacing marks removed; and what is its
//! lowercase. Computing those at runtime means several multi-level
//! property-table walks plus a recursive decomposition per character. This
//! crate answers the class question with one two-level byte lookup and the
//! normalization question with a second one that only exists for the pages
//! holding any mapping.
//!
//! Layout: `CLASS_PAGES` is one byte of class bits per code point,
//! deduplicated by page. For the pages that contain a mapping,
//! `MAP_PAGES` holds a 256-bit bitmap of the mapped code points;
//! a popcount rank gives each one's position in that page's run of
//! `RESULTS`, one `u32` per mapped code point. A
//! result holds the strip-plus-lowercase form inline when it is a single
//! character (which it is for all but a few dozen), or an index into
//! `MULTI`. Two flag bits say whether stripping or lowercasing
//! alone is the identity, from which the strip-only and lowercase-only forms
//! follow for nearly every character; the rest are listed in
//! `EXCEPTIONS`.
//!
//! The tables are generated by the `gen` binary from the
//! `unicode-normalization` and `unicode-general-category` crates at the
//! versions pinned in this crate's manifest, by walking every code point and
//! recording what those crates answer. They are checked in and only change
//! when deliberately regenerated, so the Unicode version is pinned and the
//! runtime has no dependencies. `tests/reference.rs` re-derives every entry
//! from the reference crates.
//!
//! Hangul syllables decompose algorithmically (11,172 of them, to two or
//! three jamo, with no lowercase form) and are not stored.
//!
//! The crate version's major and minor are the Unicode version of the
//! tables ([`UNICODE_VERSION`]); the patch is for changes within it.

#![no_std]

mod tables;

pub use tables::{REFERENCE_CRATES, UNICODE_VERSION};

/// Class bits of a [`class_of`] result.
pub mod class {
    /// General category `Cc`, `Cf` or `Co`.
    pub const CONTROL: u8 = 1;
    /// `char::is_whitespace` (the `White_Space` property).
    pub const WHITESPACE: u8 = 1 << 1;
    /// General category `Pc`, `Pd`, `Ps`, `Pe`, `Pi`, `Pf` or `Po`.
    pub const PUNCTUATION: u8 = 1 << 2;
    /// In one of the CJK ideograph ranges BERT pads with spaces.
    pub const CJK: u8 = 1 << 3;
    /// General category `Mn`, what accent stripping removes.
    pub const NONSPACING_MARK: u8 = 1 << 4;
    /// A precomposed Hangul syllable (`U+AC00..=U+D7A3`).
    pub const HANGUL_SYLLABLE: u8 = 1 << 5;
}

// Result word encoding (must match the generator).
const CP_MASK: u32 = 0x1F_FFFF;
const EMPTY: u32 = 0x11_0000;
const MULTI: u32 = 1 << 31;
const STRIP_IS_IDENTITY: u32 = 1 << 30;
const LOWER_IS_IDENTITY: u32 = 1 << 29;
const EXCEPTION: u32 = 1 << 28;

/// Class bits of `c` (see [`class`]).
#[inline(always)]
pub fn class_of(c: char) -> u8 {
    let cp = c as usize;
    tables::CLASS_PAGES[tables::CLASS_INDEX[cp >> 8] as usize][cp & 0xFF]
}

/// The result word for `c`, or `None` if every normalized form is `c`.
#[inline(always)]
fn result_of(c: char) -> Option<u32> {
    let cp = c as usize;
    let page = tables::MAP_INDEX[cp >> 8] as usize;
    if page == 0 {
        return None;
    }
    let bits = &tables::MAP_PAGES[page - 1];
    let w = (cp >> 6) & 3;
    let bit = 1u64 << (cp & 63);
    if bits[w] & bit == 0 {
        return None;
    }
    let mut rank = (bits[w] & (bit - 1)).count_ones() as usize;
    for &prev in &bits[..w] {
        rank += prev.count_ones() as usize;
    }
    Some(tables::RESULTS[tables::MAP_BASE[page - 1] as usize + rank])
}

/// A normalized form: a few bytes inline or a slice of the static pool.
#[derive(Clone, Copy, Debug)]
pub enum Normalized {
    /// Up to three Hangul jamo or one character, UTF-8.
    Inline([u8; 12], u8),
    Static(&'static str),
}

impl core::ops::Deref for Normalized {
    type Target = str;
    #[inline(always)]
    fn deref(&self) -> &str {
        match self {
            // SAFETY: only whole UTF-8 characters are ever encoded.
            Normalized::Inline(buf, len) => unsafe {
                core::str::from_utf8_unchecked(&buf[..*len as usize])
            },
            Normalized::Static(s) => s,
        }
    }
}

#[inline(always)]
fn inline_char(c: char) -> Normalized {
    let mut buf = [0u8; 12];
    let len = c.encode_utf8(&mut buf).len() as u8;
    Normalized::Inline(buf, len)
}

/// Decode a result word's form (the flags are ignored).
#[inline(always)]
fn decode(word: u32) -> Normalized {
    if word & MULTI != 0 {
        return Normalized::Static(tables::MULTI[(word & 0xFFFF) as usize]);
    }
    let cp = word & CP_MASK;
    if cp == EMPTY {
        return Normalized::Inline([0; 12], 0);
    }
    // SAFETY: the generator only stores scalar values.
    inline_char(unsafe { char::from_u32_unchecked(cp) })
}

/// The explicitly stored strip-only and lowercase-only forms of `c`.
#[inline(never)]
fn exception(c: char) -> (u32, u32) {
    let cp = c as u32;
    let i = tables::EXCEPTIONS
        .binary_search_by_key(&cp, |e| e.0)
        .expect("EXCEPTION flag set without an entry");
    let (_, s, l) = tables::EXCEPTIONS[i];
    (s, l)
}

/// `c` after BertNormalizer's per-character steps: NFD with nonspacing
/// marks dropped if `strip_accents`, then `char::to_lowercase` of each
/// resulting character if `lowercase`.
#[inline(always)]
pub fn normalize(c: char, strip_accents: bool, lowercase: bool) -> Normalized {
    if !strip_accents && !lowercase {
        return inline_char(c);
    }
    if strip_accents && class_of(c) & class::HANGUL_SYLLABLE != 0 {
        return hangul_jamo(c);
    }
    let Some(word) = result_of(c) else {
        return inline_char(c);
    };
    match (strip_accents, lowercase) {
        (true, true) => decode(word),
        (true, false) => {
            if word & STRIP_IS_IDENTITY != 0 {
                inline_char(c)
            } else if word & EXCEPTION == 0 && word & LOWER_IS_IDENTITY != 0 {
                decode(word)
            } else {
                decode(exception(c).0)
            }
        }
        (false, true) => {
            if word & LOWER_IS_IDENTITY != 0 {
                inline_char(c)
            } else if word & EXCEPTION == 0 && word & STRIP_IS_IDENTITY != 0 {
                decode(word)
            } else {
                decode(exception(c).1)
            }
        }
        (false, false) => unreachable!(),
    }
}

/// Canonical decomposition of a Hangul syllable into its jamo.
#[inline(never)]
fn hangul_jamo(c: char) -> Normalized {
    const S_BASE: u32 = 0xAC00;
    const L_BASE: u32 = 0x1100;
    const V_BASE: u32 = 0x1161;
    const T_BASE: u32 = 0x11A7;
    const T_COUNT: u32 = 28;
    const N_COUNT: u32 = 21 * T_COUNT;
    let s = c as u32 - S_BASE;
    let l = L_BASE + s / N_COUNT;
    let v = V_BASE + (s % N_COUNT) / T_COUNT;
    let t = s % T_COUNT;
    let mut buf = [0u8; 12];
    let mut len = 0;
    for cp in [l, v] {
        // SAFETY: jamo are valid scalar values.
        let ch = unsafe { char::from_u32_unchecked(cp) };
        len += ch.encode_utf8(&mut buf[len..]).len();
    }
    if t != 0 {
        // SAFETY: as above.
        let ch = unsafe { char::from_u32_unchecked(T_BASE + t) };
        len += ch.encode_utf8(&mut buf[len..]).len();
    }
    Normalized::Inline(buf, len as u8)
}
